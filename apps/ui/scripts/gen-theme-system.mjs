// Writes src/lib/design/theme-system.css: the light tokens (Fishnet's light block with the Caddy UI
// overrides applied) under prefers-color-scheme, for pages with no data-theme attribute. Fishnet's rule is
// "no attribute follows the system"; tokens.css alone only ships dark for :root, so this file supplies light.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../src/lib/design/', import.meta.url));

/**
 * @param {string} css
 * @param {string} selector
 * @returns {Map<string, string>}
 */
export function lightBlock(css, selector) {
	const start = css.indexOf(`${selector} {`);
	if (start < 0) throw new Error(`no ${selector} block`);
	const body = css.slice(css.indexOf('{', start) + 1, css.indexOf('}', start));
	const vars = new Map();
	for (const m of body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) vars.set(String(m[1]), String(m[2]).trim());
	return vars;
}

export function render() {
	const base = lightBlock(readFileSync(dir + 'tokens.css', 'utf8'), '[data-theme="light"]');
	const caddy = lightBlock(readFileSync(dir + 'theme-caddy.css', 'utf8'), "[data-theme='light']");
	for (const [k, v] of caddy) base.set(k, v);
	const lines = [...base].map(([k, v]) => `\t\t${k}: ${v};`).join('\n');
	return `/* Generated by scripts/gen-theme-system.mjs from tokens.css and theme-caddy.css. Do not edit. */
@media (prefers-color-scheme: light) {
	:root:not([data-theme]) {
		color-scheme: light;
${lines}
	}
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	writeFileSync(dir + 'theme-system.css', render());
	console.log('wrote theme-system.css');
}
